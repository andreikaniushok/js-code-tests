export function translate(locale, key, vars) {
  const table = MESSAGES[locale] || MESSAGES.ru;
  let text = table[key] ?? MESSAGES.ru[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function problemCount(locale, count) {
  if (locale === "en") return count === 1 ? "1 error" : `${count} errors`;
  const mod10 = count % 10;
  const mod100 = count % 100;
  const word = mod10 === 1 && mod100 !== 11 ? "ошибка" : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "ошибки" : "ошибок";
  return `${count} ${word}`;
}

export function sectionCopy(locale, id) {
  return {
    title: translate(locale, `section.${id}.title`),
    blurb: translate(locale, `section.${id}.blurb`),
  };
}
